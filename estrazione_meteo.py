def S3M_read_output_file(sPathMap,sPathMap_nc, sFileNameMap, sVarName):
    """
    Read 'sVarName' field from gzipped NetCDF file generated by S3M.
    """

    path_gz = Path(sPathMap) / sFileNameMap
    # remove .gz from filename
    sFileNameMap_nc = sFileNameMap[:-3]
    path_nc = Path(sPathMap_nc) / sFileNameMap_nc

    # --- 1. Decompress the .gz file ---
    with gzip.open(path_gz, 'rb') as f_in:
        with open(path_nc, 'wb') as f_out:
            shutil.copyfileobj(f_in, f_out)

    # --- 2. Read the variables from NetCDF ---
    # ensure sVarName is a list
    if isinstance(sVarName, str):
        sVarName = [sVarName]

    a2dMaps = {}
    ds = xr.open_dataset(path_nc, decode_times=False)

    for var in sVarName:
        if var not in ds:
            raise KeyError(f"Variable '{var}' not found in {path_nc}")
        arr = np.flipud(ds[var].values)
        a2dMaps[var] = arr  # store each 2D map

    ds.close()
    path_nc.unlink(missing_ok=True)

    return a2dMaps

